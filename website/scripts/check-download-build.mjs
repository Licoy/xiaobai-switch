import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(new URL("../../package.json", import.meta.url));
const { JSDOM } = require("jsdom");
const missing = process.argv.includes("--missing");
for (const locale of ["", "en/"]) {
  const html = readFileSync(new URL(`../dist/${locale}download/index.html`, import.meta.url), "utf8");
  const dom = new JSDOM(html, { runScripts: "outside-only", url: "https://xiaobaiswitch.com/download/" });
  const { window } = dom;
  const document = window.document;
  Object.defineProperty(window.navigator, "platform", { value: "Linux x86_64" });
  const script = [...document.querySelectorAll('script[type="module"]')].find((item) => item.textContent.includes("data-download-root"));
  assert.ok(script, "built download controller must exist");
  window.eval(script.textContent);
  const tabs = [...document.querySelectorAll('[role="tab"]')];
  assert.equal(tabs.length, 3);
  assert.equal(document.querySelector('[aria-selected="true"]').id, "os-tab-linux");
  const visible = () => [...document.querySelectorAll('[role="tabpanel"]')].filter((panel) => !panel.hidden);
  assert.equal(visible().length, 1);
  assert.equal(visible()[0].id, "os-panel-linux");
  tabs[2].dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowRight", bubbles: true }));
  assert.equal(document.activeElement.id, "os-tab-macos");
  tabs[0].dispatchEvent(new window.KeyboardEvent("keydown", { key: "End", bubbles: true }));
  assert.equal(document.activeElement.id, "os-tab-linux");
  tabs[2].dispatchEvent(new window.KeyboardEvent("keydown", { key: "Home", bubbles: true }));
  assert.equal(document.activeElement.id, "os-tab-macos");
  tabs[0].dispatchEvent(new window.KeyboardEvent("keydown", { key: "ArrowLeft", bubbles: true }));
  assert.equal(document.activeElement.id, "os-tab-linux");
  tabs[1].click();
  assert.equal(visible()[0].id, "os-panel-windows");
  const links = [...document.querySelectorAll('[role="tabpanel"] a[title]')];
  assert.equal(links.length, missing ? 7 : 8);
  assert.ok(links.every((link) => link.href.includes("/v1.0.0/")));
  assert.ok(links.every((link) => !/\.app\.tar\.gz|\.msi|\.sig|\.json/.test(link.href)));
  assert.equal(links.filter((link) => /\.tar\.gz$/.test(link.href)).length, missing ? 1 : 2);
  assert.equal(document.querySelectorAll('[role="status"]').length, missing ? 1 : 0);
  assert.ok(html.includes("v0.0.12") && html.includes("GTK 3") && html.includes("macOS 12"));
  dom.window.close();
}
console.log(`download build: bilingual links, Linux detection, tab keyboard and ${missing ? "missing asset" : "six platforms"} PASS`);
